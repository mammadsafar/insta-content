import {test,expect} from '@playwright/test';
import sharp from 'sharp';

test('owner performs real upload, feedback, changes, approval, download, publication and analytics through the interface',async({page},info)=>{
  test.skip(info.project.name!=='desktop-light'||!process.env.E2E_EMAIL||!process.env.E2E_PASSWORD,'Full write workflow uses one isolated desktop test account.');
  await page.goto('/#pages');
  await page.getByLabel('ایمیل',{exact:true}).fill(process.env.E2E_EMAIL!);
  await page.getByLabel('رمز عبور',{exact:true}).fill(process.env.E2E_PASSWORD!);
  await page.getByRole('button',{name:'ورود به روز'}).click();
  await page.getByRole('button',{name:'محتوای تازه'}).click();
  const title=`آزمون کامل مرورگر ${Date.now()}`;
  await page.getByLabel('کد یا عنوان کوتاه').fill(title);
  const image=await sharp({create:{width:800,height:1000,channels:3,background:'#c4d5cb'}}).png().toBuffer();
  await page.locator('input[type=file]').first().setInputFiles({name:'browser-fixture.png',mimeType:'image/png',buffer:image});
  await expect(page.getByText('آماده',{exact:true})).toBeVisible();
  await page.getByLabel('کپشن',{exact:true}).fill('کپشن اولیه\nخط دوم');
  await page.getByRole('button',{name:'ذخیره پیش‌نویس',exact:true}).click();
  await expect(page.getByRole('dialog',{name:title})).toBeVisible();
  await page.getByRole('button',{name:'ارسال برای تأیید',exact:true}).click();
  await page.getByRole('button',{name:/^بازخورد/}).click();
  await page.getByLabel('متن بازخورد').fill('این پیشنهاد نباید تأیید را باطل کند.');
  await page.getByRole('button',{name:'ثبت پیشنهاد',exact:true}).click();
  await page.getByRole('button',{name:'روند انتشار',exact:true}).click();
  await page.getByLabel('توضیح اصلاح الزامی').fill('متن کپشن اصلاح شود.');
  await page.getByRole('button',{name:'درخواست اصلاح',exact:true}).click();
  await page.getByRole('button',{name:'ویرایش',exact:true}).click();
  await page.getByLabel('کپشن',{exact:true}).fill('کپشن نهایی\nخط دوم حفظ می‌شود.');
  await page.getByRole('button',{name:'ذخیره پیش‌نویس',exact:true}).click();
  await page.getByRole('button',{name:'ارسال برای تأیید',exact:true}).click();
  await page.getByRole('button',{name:/^تأیید نسخه/}).click();
  await page.getByRole('button',{name:'رزرو انتشار',exact:true}).click();
  const downloaded=page.waitForEvent('download');
  await page.getByRole('link',{name:'دریافت بسته اصلی',exact:true}).click();
  expect((await downloaded).suggestedFilename()).toMatch(/\.zip$/);
  await page.getByRole('button',{name:'در اینستاگرام منتشر کردم',exact:true}).click();
  await expect(page.getByRole('heading',{name:'انتشار ثبت شده',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'ثبت آمار',exact:true}).click();
  await page.getByLabel('نقطه مشاهده').selectOption('first_hour');
  await page.getByLabel('بازدید ساعت اول',{exact:true}).fill('0');
  await page.getByLabel('حساب‌های دسترسی‌یافته',{exact:true}).fill('0');
  await page.getByRole('button',{name:'نهایی کردن مشاهده',exact:true}).click();
  await expect(page.getByRole('status').filter({hasText:'آمار نهایی شد'})).toBeVisible();
});
